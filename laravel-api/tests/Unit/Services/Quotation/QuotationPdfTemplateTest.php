<?php

namespace Tests\Unit\Services\Quotation;

use App\Models\Quotation;
use App\Models\QuotationRequest;
use App\Models\QuotationVersionItem;
use App\Models\Supplier;
use App\Services\Quotation\QuotationPdfTemplate;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Tests\TestCase;

class QuotationPdfTemplateTest extends TestCase
{
    use RefreshDatabase;

    public function test_keeps_burmese_customer_and_item_text_intact(): void
    {
        $quotation = $this->quotation([
            'product_name_snapshot' => 'တီရှပ်',
        ]);

        $html = app(QuotationPdfTemplate::class)->html($quotation, now());

        $this->assertStringContainsString('ဦးအောင်အောင်', $html);
        $this->assertStringContainsString('တီရှပ်', $html);
        $this->assertStringContainsString('ရန်ကုန်', $html);
        $this->assertStringContainsString('ကျေးဇူးတင်ပါသည်။', $html);
    }

    public function test_includes_totals_and_the_generated_footer_line(): void
    {
        $quotation = $this->quotation();

        $html = app(QuotationPdfTemplate::class)->html($quotation, now());

        $this->assertStringContainsString('TOTAL (COD)', $html);
        $this->assertStringContainsString('20,000 MMK', $html);
        $this->assertMatchesRegularExpression(
            '/Generated by .+ from CoSupply on \d{2} [A-Z][a-z]{2} \d{4}, \d{2}:\d{2}\./',
            $html,
        );
    }

    public function test_prints_a_supplier_warranty_policy_once(): void
    {
        $supplier = Supplier::factory()->create([
            'warranty_policy' => '90-day warranty against manufacturing defects.',
        ]);

        $quotation = $this->quotation([], $supplier);

        $html = app(QuotationPdfTemplate::class)->html($quotation, now());

        $this->assertStringContainsString('WARRANTY', $html);
        $this->assertSame(
            1,
            substr_count($html, '90-day warranty against manufacturing defects.'),
        );
    }

    /**
     * @param  array<string, mixed>  $itemAttributes
     */
    private function quotation(array $itemAttributes = [], ?Supplier $supplier = null): Quotation
    {
        $request = QuotationRequest::factory()->create([
            'customer_name' => 'ဦးအောင်အောင်',
            'city' => 'ရန်ကုန်',
            'township' => 'လှိုင်',
            'delivery_address' => 'အမှတ် ၁၂၃၊ လှိုင်မြို့နယ်',
        ]);

        $quotation = Quotation::factory()
            ->for($request, 'quotationRequest')
            ->priced(20000)
            ->create([
                'quotation_number' => 'QT-2026-0014',
                'version' => 2,
                'payment_terms' => 'ပစ္စည်းရောက်ချိန် ငွေသားအပြည့်ပေးချေရန်။',
                'admin_note' => 'ကျေးဇူးတင်ပါသည်။',
            ]);

        QuotationVersionItem::factory()
            ->forQuotation($quotation)
            ->create(array_merge([
                'product_name_snapshot' => 'Chair',
                'quantity' => 2,
                'unit_price' => 10000,
                'line_total' => 20000,
            ], $itemAttributes, $supplier !== null ? ['supplier_id' => $supplier->id] : []));

        return $quotation->fresh(['quotationRequest', 'items.supplier', 'createdByAdmin']);
    }
}
