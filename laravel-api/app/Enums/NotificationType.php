<?php

namespace App\Enums;

use App\Enums\Concerns\HasValues;

/**
 * In-app notification event types (LogicFlow §14).
 *
 * Customer and Admin recipient events share the `ADMIN_` / plain prefixes so
 * the notification center can group them without extra lookups.
 */
enum NotificationType: string
{
    use HasValues;

    case QUOTATION_REQUEST_RECEIVED = 'QUOTATION_REQUEST_RECEIVED';
    case QUOTATION_SENT = 'QUOTATION_SENT';
    case QUOTATION_ACCEPTED = 'QUOTATION_ACCEPTED';
    case QUOTATION_REJECTED = 'QUOTATION_REJECTED';
    case QUOTATION_CHANGE_REQUESTED = 'QUOTATION_CHANGE_REQUESTED';
    case ORDER_CONFIRMED = 'ORDER_CONFIRMED';
    case ORDER_OUT_FOR_DELIVERY = 'ORDER_OUT_FOR_DELIVERY';
    case ORDER_DELIVERED = 'ORDER_DELIVERED';
    case PAYMENT_CONFIRMED = 'PAYMENT_CONFIRMED';
    case ORDER_CANCELLED = 'ORDER_CANCELLED';

    case ADMIN_NEW_QUOTATION_REQUEST = 'ADMIN_NEW_QUOTATION_REQUEST';
    case ADMIN_QUOTATION_ACCEPTED = 'ADMIN_QUOTATION_ACCEPTED';
    case ADMIN_QUOTATION_REJECTED = 'ADMIN_QUOTATION_REJECTED';
    case ADMIN_QUOTATION_CHANGE_REQUESTED = 'ADMIN_QUOTATION_CHANGE_REQUESTED';
    case ADMIN_SUPPLIER_CONFIRMATION_REQUIRED = 'ADMIN_SUPPLIER_CONFIRMATION_REQUIRED';
    case ADMIN_CASH_COLLECTION_RECORDED = 'ADMIN_CASH_COLLECTION_RECORDED';
}
