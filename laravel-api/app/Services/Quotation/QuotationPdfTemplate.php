<?php

namespace App\Services\Quotation;

use App\Models\Quotation;
use App\Services\Setting\SettingService;
use DateTimeInterface;

/**
 * Builds the HTML body of the customer-facing quotation PDF.
 *
 * Kept separate from {@see QuotationPdfService} so the document content can be
 * asserted without parsing the binary PDF. mPDF handles wrapping, page breaks
 * and Burmese shaping, so no character-count heuristics live here.
 */
class QuotationPdfTemplate
{
    private const CYAN = '#008ecc';

    private const INK = '#1a1a1a';

    private const MUTED = '#5c5c5c';

    private const SUBTLE = '#8c8c8c';

    private const LINE = '#d4d4d4';

    private const RULE = '#ebebeb';

    public function __construct(
        private readonly SettingService $settings,
    ) {}

    public function html(Quotation $quotation, DateTimeInterface $generatedAt): string
    {
        $request = $quotation->quotationRequest;

        $companyName = (string) $this->settings->get('company_name', 'CoSupply');
        $companyPhone = (string) $this->settings->get('company_phone', '');
        $companyEmail = (string) $this->settings->get('company_email', '');
        $companyAddress = (string) $this->settings->get('company_address', '');

        $customerRows = [];

        $customerAddress = trim(implode(', ', array_filter([
            $request->township,
            $request->city,
        ])));

        foreach ([
            'Name' => $request->customer_name,
            'Company' => $request->company_name,
            'Phone' => $request->phone,
            'Email' => $request->email,
            'Address' => $customerAddress,
        ] as $label => $value) {
            $value = trim((string) $value);

            if ($value !== '') {
                $customerRows[] = [$label, $value];
            }
        }

        $deliveryLines = array_values(array_filter([
            $request->delivery_address,
            $request->landmark,
            $request->required_delivery_date !== null
                ? 'Requested delivery: '.$request->required_delivery_date->format('d M Y')
                : null,
            'Payment: Cash on Delivery',
        ]));

        $items = $quotation->items->map(function ($item, int $index): string {
            return sprintf(
                '<tr>'
                .'<td class="num">%d</td>'
                .'<td>%s</td>'
                .'<td class="right muted">%s</td>'
                .'<td class="right muted">%s</td>'
                .'<td class="right muted">%s</td>'
                .'<td class="right amount">%s</td>'
                .'</tr>',
                $index + 1,
                $this->e((string) $item->product_name_snapshot),
                $this->e((string) $item->quantity),
                $this->e($this->price((int) $item->unit_price)),
                $this->e($this->price((int) $item->discount)),
                $this->e($this->price((int) $item->line_total)),
            );
        })->implode('');

        $totals = $this->totals($quotation);

        $sections = '';

        $sections .= $this->section(
            'PAYMENT TERMS',
            $this->paragraphs((string) $quotation->payment_terms),
        );

        $warrantyPolicies = $quotation->items
            ->map(fn ($item) => $item->supplier?->warranty_policy)
            ->filter(fn ($policy) => is_string($policy) && trim($policy) !== '')
            ->map(fn ($policy) => trim($policy))
            ->unique()
            ->values();

        if ($warrantyPolicies->isNotEmpty()) {
            $sections .= $this->section(
                'WARRANTY',
                $warrantyPolicies->flatMap(fn (string $policy) => $this->paragraphs($policy))->all(),
            );
        }

        if ($quotation->admin_note !== null && $quotation->admin_note !== '') {
            $sections .= $this->section(
                'ADMIN NOTE',
                $this->paragraphs($quotation->admin_note),
            );
        }

        $customerLabelWidth = '70px';

        $customerBlock = '';
        foreach ($customerRows as [$label, $value]) {
            $customerBlock .= sprintf(
                '<tr><td class="kv-label" style="width:%s;">%s :</td><td class="kv-value">%s</td></tr>',
                $customerLabelWidth,
                $this->e($label),
                $this->e($value),
            );
        }

        $deliveryBlock = '';
        foreach ($deliveryLines as $index => $line) {
            $deliveryBlock .= sprintf(
                '<div class="%s">%s</div>',
                $index === 0 ? 'delivery-primary' : 'delivery-line',
                $this->e((string) $line),
            );
        }

        $generatedLine = sprintf(
            'Generated by %s from %s on %s.',
            $quotation->createdByAdmin?->name ?? 'Admin',
            $companyName,
            $generatedAt->format('d M Y, H:i'),
        );

        return '<!DOCTYPE html>'
            .'<html lang="en"><head><meta charset="utf-8">'
            .'<style>'.$this->styles().'</style>'
            .'</head><body>'

            // Header
            .'<table class="head"><tr>'
            .'<td class="head-left">'
            .'<div class="brand">'.$this->e($companyName).'</div>'
            .($companyAddress !== '' ? '<div class="small">'.$this->e($companyAddress).'</div>' : '')
            .'<div class="small">'.$this->e(trim($companyPhone.'  '.$companyEmail)).'</div>'
            .'</td>'
            .'<td class="head-right">'
            .'<div class="doc-type">QUOTATION</div>'
            .'<div class="doc-number">'.$this->e($quotation->quotation_number).'  |  Version '.$quotation->version.'</div>'
            .'<div class="small">Issued '.$this->e($quotation->created_at?->format('d M Y') ?? '').'</div>'
            .'<div class="small">Valid until '.$this->e($quotation->valid_until?->format('d M Y') ?? '').'</div>'
            .'</td>'
            .'</tr></table>'
            .'<div class="rule-cyan"></div>'

            // Parties
            .'<table class="parties"><tr>'
            .'<td class="party-left">'
            .'<div class="section-label">QUOTATION TO</div>'
            .($customerBlock !== '' ? '<table class="kv">'.$customerBlock.'</table>' : '')
            .'</td>'
            .'<td class="party-right">'
            .'<div class="section-label">DELIVERY DETAILS</div>'
            .$deliveryBlock
            .'</td>'
            .'</tr></table>'
            .'<div class="rule-line"></div>'

            // Items
            .'<table class="items">'
            .'<thead><tr>'
            .'<th class="col-num">#</th>'
            .'<th class="col-item">ITEM</th>'
            .'<th class="col-qty">QTY</th>'
            .'<th class="col-unit">UNIT PRICE</th>'
            .'<th class="col-disc">DISC.</th>'
            .'<th class="col-amount">AMOUNT</th>'
            .'</tr></thead>'
            .'<tbody>'.$items.'</tbody>'
            .'</table>'
            .'<div class="rule-cyan-thin"></div>'

            // Totals
            .$totals

            .$sections

            // Footer note
            .'<div class="generated">'.$this->e($generatedLine).'</div>'
            .'</body></html>';
    }

    /**
     * Footer HTML injected by the renderer so page numbers stay native.
     */
    public function footer(DateTimeInterface $generatedAt): string
    {
        return '<div class="page-footer">Page {PAGENO} of {nbpg}  |  Generated '
            .$this->e($generatedAt->format('d M Y H:i')).'</div>';
    }

    private function totals(Quotation $quotation): string
    {
        $rows = [
            ['Subtotal', $this->price((int) $quotation->subtotal)],
            ['Discount', $this->price((int) $quotation->discount)],
            ['Delivery fee', $this->price((int) $quotation->delivery_fee)],
            [
                sprintf('Service fee (%d%%)', $quotation->service_fee_percentage),
                $this->price((int) $quotation->service_fee),
            ],
        ];

        $html = '';
        foreach ($rows as [$label, $value]) {
            $html .= '<tr><td class="t-label">'.$this->e($label).'</td>'
                .'<td class="t-value">'.$this->e($value).'</td></tr>';
        }

        $html .= '<tr class="t-grand"><td class="t-label">TOTAL (COD)</td>'
            .'<td class="t-value">'.$this->e($this->money((int) $quotation->total_amount)).'</td></tr>';

        return '<table class="totals-wrap"><tr>'
            .'<td class="totals-spacer"><span class="amounts-note">All amounts in MMK</span></td>'
            .'<td class="totals-cell"><table class="totals">'.$html.'</table></td>'
            .'</tr></table>';
    }

    /**
     * @param  list<string>  $paragraphs
     */
    private function section(string $title, array $paragraphs): string
    {
        if ($paragraphs === []) {
            return '';
        }

        $body = '';
        foreach ($paragraphs as $paragraph) {
            $body .= '<p class="section-paragraph">'.$this->e($paragraph).'</p>';
        }

        return '<div class="section">'
            .'<div class="section-rule"></div>'
            .'<div class="section-title">'.$this->e($title).'</div>'
            .$body
            .'</div>';
    }

    /**
     * Split a free-text field into blank-line separated paragraphs.
     *
     * @return list<string>
     */
    private function paragraphs(string $text): array
    {
        $parts = preg_split('/\R\s*\R/', trim($text)) ?: [];
        $parts = array_map('trim', $parts);

        return array_values(array_filter($parts, static fn (string $part): bool => $part !== ''));
    }

    private function styles(): string
    {
        $cyan = self::CYAN;
        $ink = self::INK;
        $muted = self::MUTED;
        $subtle = self::SUBTLE;
        $line = self::LINE;
        $rule = self::RULE;

        return <<<CSS
body { font-family: dejavusans; color: {$ink}; font-size: 9pt; line-height: 1.35; }
table { border-collapse: collapse; width: 100%; }
.head td { vertical-align: top; padding: 0; }
.head-left { width: 55%; }
.head-right { width: 45%; text-align: right; }
.brand { font-size: 20pt; font-weight: bold; color: {$cyan}; line-height: 1.1; }
.doc-type { font-size: 16pt; font-weight: bold; color: {$muted}; line-height: 1.1; }
.doc-number { font-size: 9.5pt; font-weight: bold; color: {$cyan}; margin-top: 2px; }
.small { font-size: 8.5pt; color: {$muted}; }
.rule-cyan { border-top: 1.5px solid {$cyan}; margin: 8px 0 14px 0; }
.rule-cyan-thin { border-top: 0.75px solid {$cyan}; margin: 6px 0 0 0; }
.rule-line { border-top: 0.5px solid {$line}; margin: 12px 0 14px 0; }
.parties td { vertical-align: top; padding: 0; }
.party-left { width: 48%; padding-right: 10px; }
.party-right { width: 52%; }
.section-label { font-size: 8pt; font-weight: bold; color: {$cyan}; margin-bottom: 6px; }
.kv { width: 100%; }
.kv td { padding: 0 0 3px 0; vertical-align: top; }
.kv-label { font-size: 8.5pt; color: {$muted}; white-space: nowrap; padding-right: 6px; }
.kv-value { font-size: 9.5pt; color: {$ink}; }
.delivery-primary { font-size: 9.5pt; font-weight: bold; color: {$ink}; margin-bottom: 3px; }
.delivery-line { font-size: 8.5pt; color: {$muted}; margin-bottom: 3px; }
.items { width: 100%; }
.items th { font-size: 8pt; font-weight: bold; color: {$cyan}; padding: 0 4px 5px 4px; border-bottom: 0.5px solid {$line}; text-align: left; }
.items td { font-size: 9.5pt; padding: 6px 4px; vertical-align: top; border-bottom: 0.25px solid {$rule}; }
.items tr { page-break-inside: avoid; }
.col-num { width: 5%; }
.col-item { width: 45%; }
.col-qty { width: 8%; text-align: right; }
.col-unit { width: 15%; text-align: right; }
.col-disc { width: 10%; text-align: right; }
.col-amount { width: 17%; text-align: right; }
.num { color: {$muted}; }
.right { text-align: right; }
.muted { color: {$muted}; }
.amount { color: {$ink}; font-weight: bold; }
.totals-wrap { margin-top: 8px; }
.totals-wrap td { vertical-align: top; padding: 0; }
.totals-spacer { width: 55%; }
.amounts-note { font-size: 8pt; font-style: italic; color: {$subtle}; }
.totals-cell { width: 45%; }
.totals { width: 100%; border: 0.75px solid {$line}; }
.totals td { font-size: 9pt; padding: 4px 6px; }
.t-label { color: {$muted}; }
.t-value { text-align: right; color: {$ink}; }
.t-grand td { color: {$cyan}; font-weight: bold; font-size: 11pt; border-top: 0.5px solid {$cyan}; padding-top: 6px; }
.section { margin-top: 16px; page-break-inside: avoid; }
.section-rule { border-top: 0.75px solid {$subtle}; margin-bottom: 8px; }
.section-title { font-size: 12pt; font-weight: bold; color: {$cyan}; margin-bottom: 4px; }
.section-paragraph { font-size: 9pt; color: {$ink}; margin: 0 0 4px 0; }
.generated { margin-top: 18px; padding-top: 8px; border-top: 0.5px solid {$rule}; text-align: center; font-size: 7.5pt; color: {$subtle}; }
.page-footer { border-top: 0.5px solid {$rule}; padding-top: 4px; text-align: center; font-size: 7.5pt; color: {$subtle}; }
CSS;
    }

    private function price(int $amount): string
    {
        return number_format($amount);
    }

    private function money(int $amount): string
    {
        return number_format($amount).' MMK';
    }

    /**
     * Escape text for HTML while keeping UTF-8 (Myanmar) characters intact.
     */
    private function e(string $value): string
    {
        return htmlspecialchars($value, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8');
    }
}
